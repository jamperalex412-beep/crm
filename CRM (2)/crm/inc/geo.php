/** Оставляет только цифры, убирает 00 в начале, понимает российские номера с 8. */
function phone_normalize(string $phone): string
{
    $d = preg_replace('/\D+/', '', $phone);
    if (str_starts_with($d, '00')) $d = substr($d, 2);
    if (strlen($d) === 11 && $d[0] === '8') $d = '7' . substr($d, 1);   // 8 900 ... -> 7 900 ...
    if (strlen($d) === 10 && $d[0] === '0') $d = '380' . substr($d, 1); // 0XX XXX XX XX -> Украина
    return $d;
}

/** Возвращает ['iso'=>'UA','name'=>'Украина','code'=>'380'] или iso=null, если не определено. */
function geo_from_phone(string $phone): array
{
    $d = phone_normalize($phone);
    if (strlen($d) < 7) return ['iso' => null, 'name' => 'Не определено', 'code' => ''];

    // Казахстан делит код +7 с Россией: 7 6xx и 7 7xx
    if ($d[0] === '7' && isset($d[1]) && ($d[1] === '6' || $d[1] === '7')) {
        return ['iso' => 'KZ', 'name' => 'Казахстан', 'code' => '7'];
    }
    for ($len = 4; $len >= 1; $len--) {
        $p = substr($d, 0, $len);
        if (isset(PHONE_CODES[$p])) {
            [$iso, $name] = PHONE_CODES[$p];
            return ['iso' => $iso, 'name' => $name, 'code' => $p];
        }
    }
    return ['iso' => null, 'name' => 'Не определено', 'code' => ''];
}

/** Эмодзи-флаг по ISO2. */
function flag(?string $iso): string
{
    if (!$iso || strlen($iso) !== 2) return '🌐';
    $iso = strtoupper($iso);
    return mb_chr(0x1F1E6 + ord($iso[0]) - 65) . mb_chr(0x1F1E6 + ord($iso[1]) - 65);
}

/** Красивый вывод номера: +380 67 123 45 67 (упрощённо). */
function phone_pretty(string $phone): string
{
    $d = phone_normalize($phone);
    if ($d === '') return $phone;
    $g = geo_from_phone($d);
    $cc = $g['code'] ?: '';
    $rest = substr($d, strlen($cc));
    // Формат «916 123 45 67»: последние 4 цифры парами, остальное тройками
    if (strlen($rest) > 6) {
        $head = substr($rest, 0, -4);
        $first = strlen($head) % 3 ?: 3; // 67 123 / 916 123
        if ($first === 1) $first = strlen($head) === 4 ? 2 : 4; // 44 67 / 1234 567
        $groups = array_merge([substr($head, 0, $first)], str_split(substr($head, $first) ?: '', 3));
        $fmt = trim(implode(' ', array_filter($groups, 'strlen'))) . ' ' . substr($rest, -4, 2) . ' ' . substr($rest, -2);
    } else {
        $fmt = $rest;
    }
    return '+' . ($cc !== '' ? $cc . ' ' : '') . $fmt;
}

/** Список стран для фильтра. */
function geo_country_list(): array
{
    $out = [];
    foreach (PHONE_CODES as [$iso, $name]) $out[$iso] = $name;
    $out['KZ'] = 'Казахстан';
    asort($out);
    return $out;
}
